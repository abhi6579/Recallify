import { jsPDF } from "jspdf";

export type ResumeExportStyle = "modern" | "executive" | "minimal";

/**
 * Client & Server Document Exporter.
 * Generates ATS-optimized PDF documents using jsPDF with precise typography,
 * page splits, and margins, plus editable Word (.doc / .docx compatible) XML documents.
 */
export function exportResumeToPdf(
  resumeText: string,
  options: {
    candidateName?: string;
    roleTitle?: string;
    style?: ResumeExportStyle;
  } = {}
): Blob {
  const doc = new jsPDF({
    orientation: "portrait",
    unit: "mm",
    format: "a4",
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const margin = 16;
  const contentWidth = pageWidth - margin * 2;
  let y = margin;

  const lines = resumeText.split("\n");
  const isExecutive = options.style === "executive";

  const checkPageBreak = (neededHeight: number) => {
    if (y + neededHeight > pageHeight - margin) {
      doc.addPage();
      y = margin;
    }
  };

  for (let i = 0; i < lines.length; i++) {
    const rawLine = lines[i];
    const line = rawLine.trim();

    // 1. Candidate Name (Header)
    if (i === 0) {
      doc.setFont(isExecutive ? "times" : "helvetica", "bold");
      doc.setFontSize(18);
      doc.setTextColor(24, 32, 54);
      doc.text(line, margin, y);
      y += 7;
      continue;
    }

    // 2. Contact Info Bar
    if (i === 1) {
      doc.setFont("helvetica", "normal");
      doc.setFontSize(9);
      doc.setTextColor(100, 116, 139);
      const contactText = line.replace(/\s+\|\s+/g, "  •  ");
      doc.text(contactText, margin, y);
      y += 6;
      // Accent horizontal rule
      doc.setDrawColor(226, 232, 240);
      doc.setLineWidth(0.4);
      doc.line(margin, y, pageWidth - margin, y);
      y += 5;
      continue;
    }

    // 3. Blank line
    if (!line) {
      y += 2.5;
      continue;
    }

    // 4. Section Headings (SUMMARY, CORE SKILLS, EXPERIENCE, PROJECTS, EDUCATION, etc.)
    const isHeading = /^(SUMMARY|CORE SKILLS|EXPERIENCE|PROJECTS|EDUCATION|CERTIFICATIONS|PUBLICATIONS)\b/.test(line);
    if (isHeading) {
      checkPageBreak(12);
      y += 3;
      doc.setFont("helvetica", "bold");
      doc.setFontSize(10.5);
      doc.setTextColor(79, 70, 229); // Indigo brand accent
      doc.text(line, margin, y);
      y += 1.5;
      doc.setDrawColor(199, 210, 254);
      doc.setLineWidth(0.3);
      doc.line(margin, y, pageWidth - margin, y);
      y += 4.5;
      continue;
    }

    // 5. Bullet items
    if (rawLine.startsWith("  •") || line.startsWith("•") || line.startsWith("- ")) {
      checkPageBreak(7);
      const bulletText = line.replace(/^[•\-]\s*/, "");
      doc.setFont("helvetica", "normal");
      doc.setFontSize(9.5);
      doc.setTextColor(30, 41, 59);

      doc.circle(margin + 2, y - 1, 0.6, "F");
      const splitText = doc.splitTextToSize(bulletText, contentWidth - 6);
      doc.text(splitText, margin + 5, y);
      y += splitText.length * 4.2;
      continue;
    }

    // 6. Sub-headings (Job titles, project names)
    const isSubheading = line.includes("—") || line.includes(" - ") || line.endsWith(")");
    if (isSubheading && !line.startsWith("•")) {
      checkPageBreak(8);
      doc.setFont("helvetica", "bold");
      doc.setFontSize(10);
      doc.setTextColor(15, 23, 42);
      doc.text(line, margin, y);
      y += 4.8;
      continue;
    }

    // 7. Regular paragraph text
    checkPageBreak(6);
    doc.setFont("helvetica", "normal");
    doc.setFontSize(9.5);
    doc.setTextColor(51, 65, 85);
    const wrapped = doc.splitTextToSize(line, contentWidth);
    doc.text(wrapped, margin, y);
    y += wrapped.length * 4.2;
  }

  // Footer page numbers
  const pageCount = doc.getNumberOfPages();
  for (let p = 1; p <= pageCount; p++) {
    doc.setPage(p);
    doc.setFont("helvetica", "normal");
    doc.setFontSize(8);
    doc.setTextColor(148, 163, 184);
    doc.text(`Page ${p} of ${pageCount}  •  Generated by AutoApply`, pageWidth / 2, pageHeight - 8, { align: "center" });
  }

  return doc.output("blob");
}

/**
 * Generates an editable Word (.doc / .docx compatible) XML file
 * formatted with CSS styling that Microsoft Word, Google Docs, and LibreOffice render accurately.
 */
export function exportResumeToDocx(resumeText: string, title = "Resume"): Blob {
  const lines = resumeText.split("\n");
  let bodyHtml = "";

  for (let i = 0; i < lines.length; i++) {
    const raw = lines[i];
    const line = raw.trim();

    if (i === 0) {
      bodyHtml += `<h1 style="font-family: Arial, sans-serif; font-size: 20pt; color: #0f172a; margin-bottom: 2pt; font-weight: bold;">${escapeHtml(line)}</h1>`;
      continue;
    }
    if (i === 1) {
      bodyHtml += `<p style="font-family: Arial, sans-serif; font-size: 9.5pt; color: #64748b; margin-top: 0; margin-bottom: 12pt; border-bottom: 1.5pt solid #cbd5e1; padding-bottom: 6pt;">${escapeHtml(line)}</p>`;
      continue;
    }
    if (!line) {
      bodyHtml += `<p style="margin-bottom: 4pt;"></p>`;
      continue;
    }
    if (/^(SUMMARY|CORE SKILLS|EXPERIENCE|PROJECTS|EDUCATION|CERTIFICATIONS|PUBLICATIONS)\b/.test(line)) {
      bodyHtml += `<h2 style="font-family: Arial, sans-serif; font-size: 11pt; color: #4338ca; text-transform: uppercase; letter-spacing: 0.1em; border-bottom: 1pt solid #cbd5e1; padding-bottom: 2pt; margin-top: 10pt; margin-bottom: 4pt; font-weight: bold;">${escapeHtml(line)}</h2>`;
      continue;
    }
    if (line.startsWith("•") || line.startsWith("- ") || raw.startsWith("  •")) {
      const clean = line.replace(/^[•\-]\s*/, "");
      bodyHtml += `<p style="font-family: Arial, sans-serif; font-size: 9.5pt; color: #334155; margin: 2pt 0 2pt 14pt; line-height: 1.35;">&#8226; ${escapeHtml(clean)}</p>`;
      continue;
    }
    if (line.includes("—") || line.includes(" - ")) {
      bodyHtml += `<p style="font-family: Arial, sans-serif; font-size: 10pt; color: #0f172a; font-weight: bold; margin-top: 6pt; margin-bottom: 2pt;">${escapeHtml(line)}</p>`;
      continue;
    }
    bodyHtml += `<p style="font-family: Arial, sans-serif; font-size: 9.5pt; color: #334155; margin-bottom: 4pt; line-height: 1.4;">${escapeHtml(line)}</p>`;
  }

  const wordDocument = `
    <html xmlns:o='urn:schemas-microsoft-com:office:office' xmlns:w='urn:schemas-microsoft-com:office:word' xmlns='http://www.w3.org/TR/REC-html40'>
    <head>
      <meta charset='utf-8'>
      <title>${escapeHtml(title)}</title>
      <style>
        @page { size: 21cm 29.7cm; margin: 1.5cm 1.5cm 1.5cm 1.5cm; }
        body { font-family: 'Segoe UI', Arial, sans-serif; }
      </style>
    </head>
    <body>
      ${bodyHtml}
    </body>
    </html>
  `;

  return new Blob([wordDocument], { type: "application/msword;charset=utf-8" });
}

function escapeHtml(text: string): string {
  return text
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;");
}
